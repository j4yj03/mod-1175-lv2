    files[bundle + 'modgui.ttl'] = '\n'.join(gui) + '\n'
    files[bundle + 'presets.ttl'] = '\n'.join(preset_text) + '\n'
    files[bundle + 'modgui/grmeter.js'] = GRMETER_JS
