def number(value):
    return format(value, '.17g') if isinstance(value, float) else str(value)


def eel_number(value):
    # EEL2 does not accept C-style scientific literals in all hosts.
    text = number(value)
    if 'e' in text.lower():
        from decimal import Decimal
        text = format(Decimal(text), 'f')
    return text


def eel_lookup(name, values):
    # EEL2 globals share one storage pool; an indexed store past a declared array
    # size does not grow the array but overwrites the following variable. The mode
    # tables are therefore emitted as lookup functions instead of indexed globals.
    # EEL2 also rejects a negative literal or a parenthesis directly after `?`, so
    # the chain uses local assignment statements like the rest of the EEL2 core.
    body = [f'  v={eel_number(values[-1])};']
    body += [f'  m==={i} ? v={eel_number(x)};' for i, x in enumerate(values[:-1])]
    body += ['  v;', ');']
    return '\n'.join([f'function {name}(m) local(v) ('] + body)


def model_files(model):
    cpp = ['// Generated by tools/generate.py; edit data/model.json.',
           '#ifndef GREEN_STRIPE_MODEL_CONSTANTS_HPP',
           '#define GREEN_STRIPE_MODEL_CONSTANTS_HPP',
           'namespace greenstripe { namespace model {']
    eel = ['// Generated by tools/generate.py; SPDX-License-Identifier: MIT', '@init',
           'function gs_model_init() (']
    lookups = {'ratios': 'gs_ratio_of', 'thresholds_dbfs': 'gs_threshold_of',
               'knees_db': 'gs_knee_of'}
    addresses = {'halfband_stage1': ('gs_coefs1', 0),
                 'halfband_stage2': ('gs_coefs2', 8)}
    functions = []
    for key, value in model.items():
        if isinstance(value, str):
            continue
        if isinstance(value, list):
            cpp.append(f'static const double {key}[] = {{{", ".join(map(number, value))}}};')
            if key in lookups:
                functions.append(eel_lookup(lookups[key], value))
                continue
            variable, address = addresses[key]
            eel.append(f'  {variable}={address};')
            eel.extend(f'  {variable}[{i}]={eel_number(x)};' for i, x in enumerate(value))
        else:
            kind = 'unsigned' if isinstance(value, int) else 'double'
            cpp.append(f'static const {kind} {key} = {number(value)};')
            eel.append(f'  gs_{key}={eel_number(value)};')
    cpp += ['} }', '#endif', '']
    eel += [');', ''] + [line for f in functions for line in (f, '')]
    return {'src/dsp/ModelConstants.hpp': '\n'.join(cpp),
            'jsfx/GreenStripe76-Model.jsfx-inc': '\n'.join(eel)}


def appended_value(q, preset):
    """Value an appended control takes on a preset recall.

    Oversampling resets to its default on every recall: it is a quality/CPU
    choice, not part of the instrument sound. The transformer is a tone choice
    and is read from the preset, so a preset named for a vintage, mojo or huge
    character can bring its transformer stage with it. Only the few presets that
    set it carry a non-default value; everything else recalls to None.
    """
    if q['symbol'] == 'oversampling':
        return q['default']
    return preset.get(q['symbol'], q['default'])


def group_uri(variant, symbol):
    """Gruppen-URI: Plugin-Fragment plus Gruppen-Plugin-Suffix, ein Fragment."""
    return f'{PREFIX}{variant}-group-{symbol}'


def port(index, p, variant):
    properties = []
    if p.get('labels'):
        properties += ['lv2:integer', 'lv2:enumeration']
    if p.get('toggle'):
        properties += ['lv2:integer', 'lv2:toggled']
    if p.get('connection_optional'):
        properties += ['lv2:connectionOptional']
    lines = [f'    [ a lv2:InputPort, lv2:ControlPort; lv2:index {index};',
             f'      lv2:symbol "{p["symbol"]}"; lv2:name "{p["name"]}";']
    if p.get('group'):
        lines.append(f'      pg:group <{group_uri(variant, p["group"])}>;')
    lines += [f'      lv2:shortName "{p["short"]}"; lv2:default {number(p["default"])};',
              f'      lv2:minimum {number(p["min"])}; lv2:maximum {number(p["max"])};']
    if p.get('unit'):
        lines.append(f'      units:unit units:{p["unit"]};')
    if p.get('designation'):
        lines.append(f'      lv2:designation lv2:{p["designation"]};')
    if properties:
        lines.append('      lv2:portProperty ' + ', '.join(properties) + ';')
    for i, name in enumerate(p.get('labels', [])):
        lines.append(f'      lv2:scalePoint [ rdfs:label "{name}"; rdf:value {i} ];')
    steps = min(601, round((p['max'] - p['min']) / p['step']) + 1)
    lines.append(f'      pprops:rangeSteps {steps} ]')
    return '\n'.join(lines)


def output_port(index, p, variant):
    """Output control port (e.g. the measured gain reduction).

    Outputs are never preset-addressable and never appear in presets.ttl;
    the host reads them, the GUI only listens.
    """
    lines = [f'    [ a lv2:OutputPort, lv2:ControlPort; lv2:index {index};',
             f'      lv2:symbol "{p["symbol"]}"; lv2:name "{p["name"]}";']
    if p.get('group'):
        lines.append(f'      pg:group <{group_uri(variant, p["group"])}>;')
    lines += [f'      lv2:shortName "{p["short"]}"; lv2:default {number(p["default"])};',
              f'      lv2:minimum {number(p["min"])}; lv2:maximum {number(p["max"])};']
    if p.get('unit'):
        lines.append(f'      units:unit units:{p["unit"]};')
    lines.append('      lv2:portProperty lv2:connectionOptional;')
    steps = min(601, round((p['max'] - p['min']) / p['step']) + 1)
    lines.append(f'      pprops:rangeSteps {steps} ]')
    return '\n'.join(lines)


